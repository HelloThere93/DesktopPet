export function isExternalReferenceTool(name: string): boolean {
  return name.startsWith('mcp__') || EXTERNAL_REFERENCE_TOOLS.has(name);
}

export function labelExternalReference(name: string, content: string): string {
  if (!isExternalReferenceTool(name)) return content;
  return labelUntrustedReference(content);
}

export function labelUntrustedReference(content: string): string {
  if (!content.trim() || content.startsWith(EXTERNAL_REFERENCE_LABEL)) {
    return content;
  }
  return EXTERNAL_REFERENCE_LABEL + '\n\n' + content;
}
